-- Daily Replay v2 — persistent working orders (branch daily-replay)
-- *** PREPARED ONLY — NOT APPLIED ***
-- This file has NOT been run against any database. Applying it waits
-- for Karandeep's explicit authorization (paste into the Supabase SQL
-- editor, per DEPLOY.md), exactly as v1 did. It depends on
-- daily-replay-v1.sql (the attempts table + dr_attempt_for_owner
-- helper) and is purely additive: ONE new table + two
-- security-definer functions. No existing table, policy, or function
-- is touched.
--
-- Why this exists: refresh-resume (v1) restored fills, positions, and
-- brackets from the Decision Timeline, but working (unfilled) limit
-- orders could not be restored — limit_placed events carry no stable
-- order id, so which placements were still live at refresh time could
-- not be determined without guessing. This migration makes the SERVER
-- the authoritative store for working orders:
--
--   daily_replay_orders   one row per limit order placed during a
--                         Daily Replay attempt. The id is a
--                         client-generated uuid — the stable,
--                         persistent order identity. RLS: owner
--                         SELECT only; there are deliberately NO
--                         insert/update/delete policies, so clients
--                         can never write order state directly. All
--                         mutations happen inside the two
--                         security-definer functions below, which
--                         check ownership (via the parent attempt)
--                         and enforce the status state machine:
--
--                           working ──► filled     (filled_qty = qty)
--                           working ──► cancelled  (user cancel, or the
--                                                     engine extinguished
--                                                     the order: position
--                                                     closed / session
--                                                     reset / session end)
--                           working ──► rejected
--                           working ──► working    (filled_qty progress
--                                                     only, monotonic)
--
--                         Terminal states (filled / cancelled /
--                         rejected) are immutable at the database
--                         level: dr_update_order raises on any further
--                         change, so a cancelled or filled order can
--                         never be resurrected or rewritten.
--
-- Restore reads the rows back through the owner SELECT policy — an
-- order row is the user's own practice state, not sealed market
-- data, so no RPC is needed to read it. Only status = 'working'
-- rows are restored, with remaining qty = qty - filled_qty.
--
-- engine_order_id records the engine-local numeric id the order had
-- in the client session that placed it (diagnostics / event
-- correlation). It is NOT the identity — the uuid is — and it is not
-- rewritten on resume (a resumed engine assigns its own local ids).

-- ============ ORDERS ============
create table if not exists public.daily_replay_orders (
  -- Stable persistent order id, generated by the client at placement
  -- time (crypto.randomUUID). No server default on purpose: an order
  -- only exists once a client has deliberately placed it.
  id uuid primary key,
  attempt_id uuid not null
    references public.daily_replay_attempts(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  side text not null check (side in ('buy', 'sell')),
  order_type text not null default 'limit',
  qty numeric not null check (qty > 0),
  filled_qty numeric not null default 0 check (filled_qty >= 0),
  limit_price numeric not null check (limit_price > 0),
  status text not null default 'working'
    check (status in ('working', 'filled', 'cancelled', 'rejected')),
  -- Engine-local id in the placing session (informational only).
  engine_order_id text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (filled_qty <= qty)
);
create index if not exists daily_replay_orders_attempt_idx
  on public.daily_replay_orders (attempt_id, status);
create index if not exists daily_replay_orders_user_idx
  on public.daily_replay_orders (user_id, created_at desc);

alter table public.daily_replay_orders enable row level security;

drop policy if exists dr_orders_select_own on public.daily_replay_orders;
create policy dr_orders_select_own on public.daily_replay_orders
  for select to authenticated
  using (auth.uid() = user_id);
-- NO insert/update/delete policies: order rows are created and
-- transitioned exclusively inside the dr_*_order functions below.

-- ============ PLACE ORDER ============
-- Registers a working limit order for an ACTIVE attempt the caller
-- owns. Idempotent on p_order_id: re-submitting the same uuid (a
-- retried request, a refresh racing the placement) returns the
-- existing row instead of creating a duplicate — an order id can
-- never be placed twice.
create or replace function public.dr_place_order(
  p_attempt_id uuid,
  p_order_id uuid,
  p_side text,
  p_qty numeric,
  p_limit_price numeric,
  p_engine_order_id text default null
)
returns jsonb
language plpgsql security definer
set search_path = public, pg_temp
as $$
declare
  v_attempt public.daily_replay_attempts;
  v_row public.daily_replay_orders;
begin
  -- Checks authentication + ownership of the attempt (raises otherwise).
  v_attempt := public.dr_attempt_for_owner(p_attempt_id);
  if v_attempt.status <> 'active' then
    raise exception 'attempt is not active';
  end if;
  if p_side not in ('buy', 'sell') then
    raise exception 'side must be buy or sell';
  end if;
  if p_qty is null or p_qty <= 0 then
    raise exception 'qty must be positive';
  end if;
  if p_limit_price is null or p_limit_price <= 0 then
    raise exception 'limit_price must be positive';
  end if;

  insert into public.daily_replay_orders
    (id, attempt_id, user_id, side, order_type, qty, filled_qty,
     limit_price, status, engine_order_id)
  values
    (p_order_id, p_attempt_id, v_attempt.user_id, p_side, 'limit',
     p_qty, 0, p_limit_price, 'working', p_engine_order_id)
  on conflict (id) do nothing
  returning * into v_row;

  if v_row.id is null then
    -- The uuid already exists: this is a retry of the same placement.
    -- Return the existing row, but only if it is THIS caller's order
    -- on THIS attempt — never confirm someone else's order id.
    select * into v_row
    from public.daily_replay_orders
    where id = p_order_id
      and attempt_id = p_attempt_id
      and user_id = auth.uid();
    if not found then
      raise exception 'order id already in use';
    end if;
  end if;

  return jsonb_build_object(
    'id', v_row.id,
    'attempt_id', v_row.attempt_id,
    'side', v_row.side,
    'order_type', v_row.order_type,
    'qty', v_row.qty,
    'filled_qty', v_row.filled_qty,
    'limit_price', v_row.limit_price,
    'status', v_row.status
  );
end;
$$;

-- ============ UPDATE ORDER ============
-- The only way an order's status / filled_qty ever changes. Guards:
--   * the caller must own the order (via its row's user_id, which was
--     copied from the verified attempt at placement time);
--   * only a 'working' order can change — terminal states are final;
--   * filled_qty is monotonic non-decreasing and never exceeds qty;
--   * 'filled' requires filled_qty = qty (fully executed);
--   * 'working' requires filled_qty < qty (a fully-filled order must
--     be reported as 'filled', not left working).
-- p_filled_qty may be null to keep the current value.
create or replace function public.dr_update_order(
  p_order_id uuid,
  p_status text,
  p_filled_qty numeric default null
)
returns jsonb
language plpgsql security definer
set search_path = public, pg_temp
as $$
declare
  v_row public.daily_replay_orders;
  v_filled numeric;
begin
  if auth.uid() is null then
    raise exception 'not authenticated';
  end if;
  select * into v_row
  from public.daily_replay_orders
  where id = p_order_id;
  if not found then
    raise exception 'order not found';
  end if;
  if v_row.user_id <> auth.uid() then
    raise exception 'permission denied: not your order';
  end if;
  if v_row.status <> 'working' then
    raise exception 'order is already % (terminal)', v_row.status;
  end if;
  if p_status not in ('working', 'filled', 'cancelled', 'rejected') then
    raise exception 'invalid status %', p_status;
  end if;

  v_filled := coalesce(p_filled_qty, v_row.filled_qty);
  if v_filled < v_row.filled_qty then
    raise exception 'filled_qty cannot decrease (% -> %)',
      v_row.filled_qty, v_filled;
  end if;
  if v_filled > v_row.qty then
    raise exception 'filled_qty % exceeds order qty %', v_filled, v_row.qty;
  end if;
  if p_status = 'filled' and v_filled <> v_row.qty then
    raise exception 'a filled order must have filled_qty = qty (% of %)',
      v_filled, v_row.qty;
  end if;
  if p_status = 'working' and v_filled >= v_row.qty then
    raise exception 'filled_qty % of % must be reported as filled',
      v_filled, v_row.qty;
  end if;

  update public.daily_replay_orders
  set status = p_status,
      filled_qty = v_filled,
      updated_at = now()
  where id = p_order_id
  returning * into v_row;

  return jsonb_build_object(
    'id', v_row.id,
    'attempt_id', v_row.attempt_id,
    'side', v_row.side,
    'order_type', v_row.order_type,
    'qty', v_row.qty,
    'filled_qty', v_row.filled_qty,
    'limit_price', v_row.limit_price,
    'status', v_row.status
  );
end;
$$;

