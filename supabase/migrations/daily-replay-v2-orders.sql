revoke all on function public.dr_place_order(uuid, uuid, text, numeric, numeric, text) from public;
revoke all on function public.dr_update_order(uuid, text, numeric) from public;

grant execute on function public.dr_place_order(uuid, uuid, text, numeric, numeric, text) to authenticated;
grant execute on function public.dr_update_order(uuid, text, numeric) to authenticated;
